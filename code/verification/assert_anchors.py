def walk(o):
    if isinstance(o, dict):
        for v in o.values(): yield from walk(v)
    elif isinstance(o, (list, tuple)):
        for v in o: yield from walk(v)
    elif isinstance(o, (int, float)) and not isinstance(o, bool):
        yield float(o)


def has(vals, x, tol=5e-4):
    return any(abs(v - x) <= tol or abs(v + x) <= tol for v in vals)


bad, checked = [], 0
for claim, nums, src in ANCHORS:
    if src is None:
        continue                                    # 출처 미고정 — 아래에서 별도 보고
    p = f"{OUT}/{src}"
    if not os.path.exists(p):
        bad.append((claim, src, "출처 JSON 없음", nums)); continue
    vals = list(walk(json.load(open(p, encoding="utf-8"))))
    miss = [x for x in nums if not has(vals, x)]
    checked += len(nums)
    if miss:
        bad.append((claim, src, "출처에 없음", miss))

unpinned = [c for c, _, s in ANCHORS if s is None]
print(f"앵커 {len(ANCHORS)}청구 · 수치 {checked}개 대조")
for claim, src, why, nums in bad:
    print(f"  🔴 {claim:<28} {src or '-':<10} {why}: {nums}")
if unpinned:
    print(f"  ⚠️  출처 미고정 {len(unpinned)}건: {', '.join(unpinned)}")
retired_present = [c for c, _, _ in ANCHORS if c in RETIRED_ANCHORS]
if retired_present:
    print(f"  ℹ️  폐기 앵커 {len(retired_present)}건 (산출물 보존, 원고 비인용):")
    for c in retired_present: print(f"      {c} — {RETIRED_ANCHORS[c]}")
missing_retired = [c for c in RETIRED_ANCHORS if c not in {a[0] for a in ANCHORS}]
if missing_retired:
    print(f"  🔴 RETIRED_ANCHORS 에 있으나 ANCHORS 에 없는 항목: {missing_retired}")
print(f"\n총평: 불일치 {len(bad)}건 · 폐기 앵커 {len(retired_present)}건")
sys.exit(1 if (bad or missing_retired) else 0)
